create table if not exists public.erp_number_sequences (
  kind text primary key,
  prefix text not null,
  last_value bigint not null default 0,
  updated_at timestamptz not null default now()
);

insert into public.erp_number_sequences(kind,prefix,last_value) values
 ('STUDENT','LDMS',0),('TEACHER','LDT',0),('LETTER','LDMEA/'||extract(year from current_date)::text||'/',0)
on conflict (kind) do nothing;

create or replace function public.ldmea_next_number(p_kind text)
returns text language plpgsql security definer set search_path=public as $$
declare k text:=upper(trim(p_kind)); n bigint; p text;
begin
  insert into public.erp_number_sequences(kind,prefix,last_value)
  values(k, case when k='STUDENT' then 'LDMS' when k='TEACHER' then 'LDT' when k='LETTER' then 'LDMEA/'||extract(year from current_date)::text||'/' else k||'-' end,0)
  on conflict(kind) do nothing;
  update public.erp_number_sequences set last_value=last_value+1,updated_at=now() where kind=k returning last_value,prefix into n,p;
  return p||lpad(n::text,6,'0');
end $$;

