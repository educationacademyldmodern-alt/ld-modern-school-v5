-- Safe auto-number triggers for NEW rows only. Existing values are preserved.
create or replace function public.ldmea_students_auto_id() returns trigger language plpgsql as $$
begin
 if new.student_id is null or btrim(new.student_id)='' then new.student_id:=public.ldmea_next_number('STUDENT'); end if;
 return new;
end $$;
create or replace function public.ldmea_teachers_auto_id() returns trigger language plpgsql as $$
begin
 if new.employee_id is null or btrim(new.employee_id)='' then new.employee_id:=public.ldmea_next_number('TEACHER'); end if;
 return new;
end $$;
do $$ begin
